// Compile the source artwork into a native-resolution, lossless game atlas.
// Run against npm run dev after changing the original sheets or extraction code.
import {chromium} from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage();
await page.goto((process.env.GAME_URL||'http://localhost:3000')+'/?sourceArt=1',{waitUntil:'networkidle'});
await page.waitForFunction(async()=>{const m=await import('/src/game/polishedSprites.ts');return m.getArtStatus().ready;});
const result=await page.evaluate(async()=>{
 const {getSpriteBank}=await import('/src/game/sprites.ts');const bank=getSpriteBank();
 const end=Date.now()+10000;
 while(!bank.costumes.yacht_black_vip.polished || bank.costumes.yacht_black_vip.swim[0].width!==108 || bank.props.goldenLambo[0].width!==176 || bank.props.scooterPickup[0].height!==50){if(Date.now()>end)throw new Error('Source artwork did not finish loading');await new Promise(r=>setTimeout(r,50));}
 const frames=[];
 const visit=(value,path)=>{
  if(value instanceof HTMLCanvasElement){
   const c=document.createElement('canvas');c.width=path==='props.superYacht'?340:value.width;c.height=path==='props.superYacht'?192:value.height;
   const ctx=c.getContext('2d');ctx.imageSmoothingEnabled=false;ctx.drawImage(value,0,0,c.width,c.height);frames.push({path,canvas:c});
  }else if(value&&typeof value==='object')Object.entries(value).forEach(([key,v])=>visit(v,path?path+'.'+key:key));
 };
 visit(bank.costumes,'costumes');visit(bank.marco,'marco');visit(bank.boss,'boss');
 for(const key of ['superYacht','scooterPickup','goldenLambo'])visit(bank.props[key],'props.'+key);
 const width=1024;let x=1,y=1,row=0;const metadata=[];
 for(const {path,canvas}of frames){if(x+canvas.width+1>width){x=1;y+=row+2;row=0;}metadata.push({path,x,y,w:canvas.width,h:canvas.height});x+=canvas.width+2;row=Math.max(row,canvas.height);}
 const atlas=document.createElement('canvas');atlas.width=width;atlas.height=y+row+1;
 const ctx=atlas.getContext('2d');ctx.imageSmoothingEnabled=false;
 frames.forEach((f,i)=>ctx.drawImage(f.canvas,metadata[i].x,metadata[i].y));
 return {metadata,data:atlas.toDataURL('image/png').split(',')[1],width,height:atlas.height};
});
await fs.writeFile('public/assets/polish/game-atlas-v3.png',Buffer.from(result.data,'base64'));
await fs.writeFile('src/game/artAtlas.ts','// Generated by npm run art:pack. Coordinates are native game pixels.\nexport const ART_ATLAS = '+JSON.stringify(result.metadata)+' as const;\n');
console.log(`Packed ${result.metadata.length} sprites in ${result.width}×${result.height}, ${(Buffer.from(result.data,'base64').length/1024).toFixed(0)} KB.`);
await browser.close();
